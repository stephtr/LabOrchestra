// Run before the client is built (see package.json). Makes what runtime widgets need, in public/_lo/:
//  - react.js, react-dom.js, react-dom-client.js, jsx-runtime.js, widget.js: modules that re-export the host's own instances (the host puts them
//    in globalThis.__lo), so that a widget and the host share one React. The import map in index.html points the widgets' imports at them.
//  - tailwind-compiler.js: the Tailwind compiler as one script. The *server* runs it (in an embedded JS engine) to make one stylesheet for the
//    host and all widgets; browsers never load it.
import fs from 'node:fs';
import { createRequire } from 'node:module';
import { buildSync } from 'esbuild';

const require = createRequire(import.meta.url);
const out = 'public/_lo';
fs.mkdirSync(out, { recursive: true });

const names = (module) => Object.keys(module).filter((n) => n !== 'default' && /^[A-Za-z_$][\w$]*$/.test(n));
const shim = (key, exports) =>
	`// generated by gen-shims.mjs\nconst m = globalThis.__lo[${JSON.stringify(key)}];\nexport default m.default ?? m;\n` + exports.map((n) => `export const ${n} = m.${n};`).join('\n') + '\n';

for (const [key, file] of [
	['react', 'react'],
	['react/jsx-runtime', 'jsx-runtime'],
	['react-dom', 'react-dom'],
	['react-dom/client', 'react-dom-client'],
]) {
	fs.writeFileSync(`${out}/${file}.js`, shim(key, names(require(key))));
}
const sdk = fs.readFileSync('src/widget-sdk.tsx', 'utf8');
fs.writeFileSync(`${out}/widget.js`, shim('@laborchestra/widget', [...sdk.matchAll(/^export (?:const|function|class) (\w+)/gm)].map((m) => m[1])));

// the theme of the host (src/styles.css) goes into the compiler, so that widgets can use bg-brand and the like
const theme = /@theme\s*\{([^}]*)\}/.exec(fs.readFileSync('src/styles.css', 'utf8'))?.[1] ?? '';
buildSync({
	stdin: {
		contents: `import { compile } from 'tailwindcss';
import theme from 'tailwindcss/theme.css';
import preflight from 'tailwindcss/preflight.css';
import utilities from 'tailwindcss/utilities.css';
globalThis.makeCompiler = () => compile(\`@layer theme, base, components, utilities;@layer theme{\${theme}}@layer base{\${preflight}}@layer utilities{\${utilities}}@theme{${theme.replace(/[`\\$]/g, '\\$&')}}\`);`,
		resolveDir: process.cwd(),
	},
	bundle: true,
	minify: true,
	format: 'iife',
	target: 'es2022',
	loader: { '.css': 'text' },
	outfile: `${out}/tailwind-compiler.js`,
	logLevel: 'error',
});
